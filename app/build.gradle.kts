configurations.configureEach {
    if (!name.startsWith("detekt")) {
        // Kotlin 1.9 JVM/Android classes come from kotlin-stdlib. The legacy
        // common metadata artifact has no Android runtime variant; retaining it
        // makes AGP lint's artifact view disagree with strict dependency locks.
        exclude(group = "org.jetbrains.kotlin", module = "kotlin-stdlib-common")
    }

    resolutionStrategy.eachDependency {
        when {
            !this@configureEach.name.startsWith("detekt") &&
                requested.group == "org.jetbrains.kotlin" &&
                requested.name.startsWith("kotlin-stdlib") -> {
                useVersion("1.9.24")
                because("production and test classpaths must match the Kotlin 1.9.24 compiler metadata")
            }
            !this@configureEach.name.startsWith("detekt") &&
                requested.group == "org.jetbrains.kotlinx" &&
                requested.name.startsWith("kotlinx-coroutines") -> {
                useVersion("1.8.1")
                because("last reviewed coroutines line compatible with Kotlin 1.9.24")
            }
            requested.group == "androidx.compose.ui" &&
                requested.name.startsWith("ui-test") -> {
                useVersion("1.6.8")
                because("Compose UI tests must stay aligned with the Kotlin 1.9 Compose runtime")
            }
            requested.group == "io.netty" -> {
                useVersion("4.1.137.Final")
                because("security floor for 2025/2026 Netty codec and TLS CVEs")
            }
            requested.group == "com.google.protobuf" && requested.name == "protobuf-java" -> {
                useVersion("3.25.5")
                because("fix CVE-2024-7254 in Android test/build tooling")
            }
            requested.group == "com.google.protobuf" && requested.name == "protobuf-javalite" -> {
                useVersion("4.28.2")
                because("fix CVE-2024-7254 in MediaPipe runtime dependencies")
            }
            requested.group == "commons-io" && requested.name == "commons-io" -> {
                useVersion("2.14.0")
                because("fix CVE-2024-47554 in Android test tooling")
            }
            requested.group == "com.google.guava" && requested.name == "guava" -> {
                useVersion("33.7.1-android")
                because("remove CVE-2023-2976 and CVE-2020-8908 from Android tooling")
            }
        }
    }
}

