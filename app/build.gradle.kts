fun validatedApiUrl(name: String, value: String, allowHttp: Boolean): String {
    val uri = URI(value)
    require(uri.isAbsolute && !uri.host.isNullOrBlank() && uri.rawUserInfo == null &&
        uri.rawQuery == null && uri.rawFragment == null &&
        (uri.path.isNullOrEmpty() || uri.path == "/")) {
        "$name must be an absolute origin without credentials/path/query/fragment"
    }
    require(uri.scheme == "https" || (allowHttp && uri.scheme == "http")) {
        "$name must use HTTPS${if (allowHttp) " or explicitly allowed local HTTP" else ""}"
    }
    if (uri.scheme == "http") {
        require(uri.host in setOf("localhost", "127.0.0.1", "10.0.2.2")) {
            "$name may use cleartext only for an explicit local development host"
        }
    }
    return value.trimEnd('/')
}

fun quoted(value: String): String = "\"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""

