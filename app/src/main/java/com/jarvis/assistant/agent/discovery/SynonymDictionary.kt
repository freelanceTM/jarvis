        setOf("выключ", "выруби", "выруб", "погаси", "потуш", "деактивир", "закрой", "стоп", "отключ"),
        
        // Фонарик / Свет
        setOf("фонар", "свет", "посвет", "свети", "вспышк", "подсвет", "фонарик"),
        
        // Громкость / Звук
        setOf("громк", "звук", "тише", "тиш", "потише", "громче", "погромче", "децибел", "volume"),
        setOf("прибав", "увелич", "повыс", "добав", "подним"),
        setOf("убав", "уменьш", "пониз", "снизь", "сниж"),
        
        // Батарея / Заряд
        setOf("батаре", "заряд", "аккумулят", "аккум", "процент", "энерг"),
        
        // Время / Дата
        setOf("врем", "час", "минут", "дат", "числ", "день", "сегодн"),
        
